#!/usr/bin/env python3
"""The 2.7 linker's disassembler data (0x004a194e-0x004a769c of mwldeppc.exe 3.0.4) as C, for
src/linker/PPCDisassembler27.c: one packed struct, PPCDis27, with the original's bytes in their layout (its tables
are read past their ends, and 2.7 aligns its objects on 2 bytes), a member at each object the code names and at
each pointer (initialised with the member or handler it points at), and a macro data_XXXXXXXX for each
member.

    python tools/gen_disdata.py ORIGINAL NAMES OUT

    python tools/gen_disdata.py build/compilers/GC/2.7/mwldeppc.exe config/LD_2_7/disassembler_names.txt OUT
    (OUT's contents are the data section of src/linker/PPCDisassembler27.c, between its declarations and its code)

NAMES lists the objects the code names, one address (hex) per line, and the handlers (address name) the handler
table points at."""
import struct
import sys

LOW, HIGH = 0x004A194E, 0x004A769C


def sections(image):
    pe = struct.unpack_from("<I", image, 0x3C)[0]
    count = struct.unpack_from("<H", image, pe + 6)[0]
    optional = struct.unpack_from("<H", image, pe + 20)[0]
    base = struct.unpack_from("<I", image, pe + 24 + 28)[0]
    result = []
    for i in range(count):
        at = pe + 24 + optional + 40 * i
        name = image[at:at + 8].rstrip(b"\0").decode()
        vsize, va, rsize, raw = struct.unpack_from("<IIII", image, at + 8)
        result.append((name, base + va, vsize, raw))
    return base, result


def relocations(image, base, secs):
    reloc = [s for s in secs if s[0] == ".reloc"][0]
    at, end = reloc[3], reloc[3] + reloc[2]
    result = set()
    while at < end:
        page, size = struct.unpack_from("<II", image, at)
        if size == 0:
            break
        for k in range((size - 8) // 2):
            entry = struct.unpack_from("<H", image, at + 8 + 2 * k)[0]
            if entry >> 12 == 3:
                result.add(base + page + (entry & 0xFFF))
        at += size
    return result


def main():
    image = open(sys.argv[1], "rb").read()
    base, secs = sections(image)
    data = [s for s in secs if s[0] == ".data"][0]

    def byte_at(va):
        return image[va - data[1] + data[3]]

    def word_at(va):
        return struct.unpack_from("<I", image, va - data[1] + data[3])[0]

    pointers = sorted(a for a in relocations(image, base, secs) if LOW <= a < HIGH)
    handlers = {}
    named = set()
    for line in open(sys.argv[2]):
        line = line.split("#")[0].split()
        if not line:
            continue
        if len(line) == 2:
            handlers[int(line[0], 16)] = line[1]
        else:
            named.add(int(line[0], 16))
    targets = {word_at(p) for p in pointers}
    for t in targets:
        if not (LOW <= t < HIGH) and t not in handlers:
            sys.exit(f"pointer to {t:08x}: no handler named")
    starts = {LOW} | {a for a in named if LOW <= a < HIGH} | {t for t in targets if LOW <= t < HIGH}
    starts |= set(pointers) | {p + 4 for p in pointers}
    starts = sorted(a for a in starts if a < HIGH)
    pointer_set = set(pointers)

    members = []   # (address, kind, size, init)
    for i, start in enumerate(starts):
        end = starts[i + 1] if i + 1 < len(starts) else HIGH
        if start in pointer_set:
            target = word_at(start)
            members.append((start, "pointer", 4, target))
            continue
        members.append((start, "bytes", end - start, bytes(byte_at(a) for a in range(start, end))))

    # Runs of pointers that start at a named object (or a target) and meet no other named object: arrays.
    merged = []
    i = 0
    while i < len(members):
        m = members[i]
        if m[1] == "pointer":
            j = i + 1
            while j < len(members) and members[j][1] == "pointer" and members[j][0] not in named \
                    and members[j][0] not in targets:
                j += 1
            merged.append((m[0], "pointers", 4 * (j - i), [x[3] for x in members[i:j]]))
            i = j
        else:
            merged.append(m)
            i += 1

    def name(address):
        return f"d_{address:08x}"

    def ref(target):
        if target in handlers:
            return f"(void *){handlers[target]}"
        owner = max(m for m in merged if m[0] <= target)
        if owner[0] != target:
            sys.exit(f"pointer into {owner[0]:08x} at {target:08x}")
        return f"&PPCDis27.{name(target)}" if owner[1] == "pointers" else f"PPCDis27.{name(target)}"

    def describe(value):
        text = value.rstrip(b"\0")
        if text and all(32 <= c < 127 for c in text) and value[len(text):] == b"\0" * (len(value) - len(text)):
            return text.decode()
        return None

    out = []
    out.append("/* Generated by tools/gen_disdata.py from the 2.7 linker (0x004a194e-0x004a769c): do not edit. */")
    out.append("#pragma options align = packed")
    out.append("struct PPCDis27Data {")
    for address, kind, size, init in merged:
        if kind == "bytes":
            out.append(f"    unsigned char {name(address)}[{size}];")
        else:
            out.append(f"    void *{name(address)}[{size // 4}];")
    out.append("};")
    out.append("#pragma options align = reset")
    out.append("")
    out.append("struct PPCDis27Data PPCDis27 = {")
    for address, kind, size, init in merged:
        if kind == "bytes":
            text = describe(init)
            if text is not None and '"' not in text and "\\" not in text and "?" not in text:
                out.append(f'    /* 0x{address:08x} */ "{text}",')
            else:
                out.append(f"    /* 0x{address:08x} */ {{" + ", ".join(f"0x{b:02x}" for b in init) + "},")
        else:
            out.append(f"    /* 0x{address:08x} */ {{" + ", ".join(ref(t) for t in init) + "},")
    out.append("};")
    out.append("")
    for address, kind, size, init in merged:
        text = describe(init) if kind == "bytes" else None
        note = f'"{text}"' if text is not None else (f"{size // 4} pointers" if kind == "pointers" else f"{size} bytes")
        ctype = "(void **)" if kind == "pointers" else "(char *)"
        out.append(f"#define data_{address:08x} ({ctype}PPCDis27.{name(address)})  /* {note} */")
    open(sys.argv[3], "w", newline="\n").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
